function detectFramework(text, title) {
  const hay = `${text || ""} ${title || ""}`;
  if (/발표|프레젠테이션|ppt|피피티|구술|스피치/i.test(hay)) return FRAMEWORKS.presentation;
  return FRAMEWORKS.report;
}

