/**
 * 평가기준 텍스트를 분석해 준비 방향 블록 목록을 반환한다.
 * 첫 블록은 항상 결과물 유형별 '틀', 이어서 매칭되는 기준별 상세 팁이 온다.
 * @param {string} text 평가기준 텍스트
 * @param {string} [title] 수행평가 이름 (틀 유형 추정에 사용)
 */
function analyzeCriteria(text, title) {
  const normalized = (text || "").trim();

  const framework = detectFramework(text, title);
  const blocks = [{ ...framework, isFramework: true }];

  const matched = CRITERIA_GUIDE.filter((item) =>
    item.keywords.some((keyword) => normalized.includes(keyword))
  );

  if (matched.length > 0) {
    blocks.push(...matched);
  } else {
    blocks.push(GENERIC_BLOCK);
  }

  return blocks;
}
