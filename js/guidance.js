/**
 * 평가기준 텍스트를 분석해 매칭되는 가이드 블록 목록을 반환한다.
 * 매칭되는 키워드가 없으면 일반 전략을 반환한다.
 */
export function analyzeCriteria(text) {
  const normalized = (text || "").trim();
  if (!normalized) return [];

  const matched = CRITERIA_GUIDE.filter((item) =>
    item.keywords.some((keyword) => normalized.includes(keyword))
  );

  return matched.length > 0 ? matched : [GENERIC_TIPS];
}
